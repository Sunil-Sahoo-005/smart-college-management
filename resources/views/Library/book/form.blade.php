    <script>
        function bkAdj(delta) {
            const inp = document.getElementById('bkCopiesVal');
            let v = parseInt(inp.value || 1) + delta;
            if (v < 1) v = 1;
            if (v > 100) v = 100;
            inp.value = v;
        }

        function bkPreviewImg(input) {
            if (!input.files || !input.files[0]) return;
            const file = input.files[0];
            if (file.size > 2 * 1024 * 1024) {
                alert('Image must be under 2 MB');
                input.value = '';
                return;
            }
            const reader = new FileReader();
            reader.onload = function(e) {
                const wrap = document.getElementById('bkImgWrap');
                const img = document.getElementById('bkImgPreview');
                img.src = e.target.result;
                wrap.style.display = 'block';
                const zone = document.getElementById('bkUploadZone');
                if (zone) zone.style.display = 'none';
            };
            reader.readAsDataURL(file);
        }

        function bkRemoveImg() {
            const wrap = document.getElementById('bkImgWrap');
            const input = document.getElementById('bkCoverInput');
            const zone = document.getElementById('bkUploadZone');
            wrap.style.display = 'none';
            input.value = '';
            if (zone) zone.style.display = 'block';
        }
    </script>
    <script>
    $(document).ready(function () {
        const oldRowId = "{{ old('row_id', $books->row_id ?? '') }}";
        const oldShelfId = "{{ old('shelf_id', $books->shelf_id ?? '') }}";
        const oldRoomId = "{{ old('room_id', $books->room_id ?? '') }}";

        function loadRows(roomId, selectedRowId = '') {
            $('#row_id').html('<option value="">Loading...</option>');
            $('#shelf_id').html('<option value="">Select Shelf</option>');

            if (!roomId) {
                $('#row_id').html('<option value="">Select Row</option>');
                return;
            }

            $.ajax({
                url: "{{ route('admin.books.rows_by_room') }}",
                type: "GET",
                data: { room_id: roomId },
                success: function (rows) {
                    let options = '<option value="">Select Row</option>';
                    rows.forEach(function (row) {
                        const selected = selectedRowId == row.id ? 'selected' : '';
                        options += `<option value="${row.id}" ${selected}>${row.name}</option>`;
                    });
                    $('#row_id').html(options);

                    if (selectedRowId) {
                        loadShelves(selectedRowId, oldShelfId);
                    }
                }
            });
        }

        function loadShelves(rowId, selectedShelfId = '') {
            $('#shelf_id').html('<option value="">Loading...</option>');

            if (!rowId) {
                $('#shelf_id').html('<option value="">Select Shelf</option>');
                return;
            }

            $.ajax({
                url: "{{ route('admin.books.shelves_by_row') }}",
                type: "GET",
                data: { row_id: rowId },
                success: function (shelves) {
                    let options = '<option value="">Select Shelf</option>';
                    shelves.forEach(function (shelf) {
                        const selected = selectedShelfId == shelf.id ? 'selected' : '';
                        options += `<option value="${shelf.id}" ${selected}>${shelf.name}</option>`;
                    });
                    $('#shelf_id').html(options);
                }
            });
        }

        $('#room_id').on('change', function () {
            const roomId = $(this).val();
            loadRows(roomId);
        });

        $('#row_id').on('change', function () {
            const rowId = $(this).val();
            loadShelves(rowId);
        });

        if (oldRoomId) {
            loadRows(oldRoomId, oldRowId);
        }
    });
</script>
@endsection
